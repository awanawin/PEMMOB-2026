import 'package:flutter/material.dart';
import 'package:webview_flutter/webview_flutter.dart';

/// HTML asli dari Stitch dipertahankan untuk menjaga kemiripan visual.
class LoginSiswa1Screen extends StatefulWidget {
  const LoginSiswa1Screen({super.key});

  @override
  State<LoginSiswa1Screen> createState() => _LoginSiswa1ScreenState();
}

class _LoginSiswa1ScreenState extends State<LoginSiswa1Screen> {
  late final WebViewController _controller;

  @override
  void initState() {
    super.initState();
    _controller = WebViewController()
      ..setJavaScriptMode(JavaScriptMode.unrestricted)
      ..setBackgroundColor(const Color(0xFFF9F9FF))
      ..loadFlutterAsset('assets/screens/login_siswa_1/index.html');
  }

  @override
  Widget build(BuildContext context) => Scaffold(
    body: SafeArea(child: WebViewWidget(controller: _controller)),
  );
}
